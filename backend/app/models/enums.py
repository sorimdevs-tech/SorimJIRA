    SPRINT_ENDED = "SPRINT_ENDED"
    DEADLINE_REMINDER = "DEADLINE_REMINDER"
    APPROVAL_REQUIRED = "APPROVAL_REQUIRED"
    DEFECT_RAISED = "DEFECT_RAISED"
    COMMENT_ADDED = "COMMENT_ADDED"
